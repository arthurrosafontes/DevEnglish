export function icon(name, size = 22, cls = "") {
  return `<svg class="ic ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] || ""}</svg>`;
}

export function toast(msg, ms = 2400) {
  let el = document.getElementById("toast");
  if (!el) {
    el = document.createElement("div");
    el.id = "toast";
    document.body.appendChild(el);
  }
  el.textContent = msg;
  el.classList.add("show");
  clearTimeout(el._t);
  el._t = setTimeout(() => el.classList.remove("show"), ms);
}

/** Modal simples. buttons: [{label, value, cls}] → Promise<value> */
export function modal(html, buttons = [{ label: "OK", value: true, cls: "primary" }]) {
  return new Promise((resolve) => {
    const wrap = document.createElement("div");
    wrap.className = "modal-wrap";
    wrap.innerHTML = `<div class="modal" role="dialog" aria-modal="true">
      <div class="modal-body">${html}</div>
      <div class="modal-actions">${buttons.map((b, i) => `<button class="btn ${b.cls || "ghost"}" data-i="${i}">${esc(b.label)}</button>`).join("")}</div>
    </div>`;
    wrap.addEventListener("click", (e) => {
      const b = e.target.closest("[data-i]");
      if (!b) return;
      wrap.remove();
      resolve(buttons[+b.dataset.i].value);
    });
    document.body.appendChild(wrap);
  });
}

export function fmtTime(secs) {
  const m = Math.floor(secs / 60), s = Math.round(secs % 60);
  return m ? `${m} min ${s ? s + " s" : ""}`.trim() : `${s} s`;
}

export function fmtDate(str) {
  const [y, m, d] = str.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString("pt-BR", { weekday: "short", day: "2-digit", month: "short" });
}
